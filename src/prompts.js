export const MEAL_PLANNER_PROMPT = `你是菜品规划助手。根据用户提供的食材、口味偏好或用餐场景，列出 2-4 道推荐菜品。

要求：
- 菜品之间尽量互补（一荤一素、一汤一炒等）
- 优先使用用户提到的食材
- 如果用户没有明确食材，根据场景合理推荐

返回严格 JSON 格式：
{ "dishes": ["菜名1", "菜名2", "菜名3"] }

只返回 JSON，不要多余文字。`;

/**
 * 菜品研究员的提示词生成函数
 *
 * 这个节点由 Send 并行调用——每道菜一个独立分支。
 * 因为每个分支研究的菜品不同，所以用函数动态生成提示词。
 *
 * 例如 plannedDishes = ["番茄炒蛋", "青椒土豆丝", "菌菇豆腐汤"]
 * 会产生 3 个并行 Send，每个 Send 的 currentDish 不同，
 * 对应的提示词也不同。
 *
 * @param {string} dish - 当前分支要研究的菜品名
 * @returns {string} 该分支的系统提示词
 */
export function createDishResearcherPrompt(dish) {
  return `你是菜品研究专家。请对"${dish}"进行简要分析，包括：
1. 主要食材（3-5 种）
2. 烹饪难度（简单/中等/困难）和预计时间
3. 营养亮点（热量水平、蛋白质、特色营养素）
4. 核心做法（3-4 步概括）

用 150 字以内简洁回答，不要客套开场。`;
}

