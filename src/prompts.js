// 增强版图在标准 ReAct loop 基础上引入了多种 LangGraph 核心模式：
//
// 【多 Agent（Supervisor + Sub-graph）】
//  1. 总调度 supervisor —— 决定分派给哪个专家
//  2. 烹饪专家 chef_agent（子图）—— 菜谱/购物/营养/天气工具
//  3. 检索专家 research_agent（子图）—— 文档检索/联网搜索/图片分析工具
//
// 【Send 并行扇出】
//  4. 意图分类器 intent_classifier —— 入口路由
//  5. 菜品规划器 meal_planner —— 多菜场景识别
//  6. 菜品研究员 dish_researcher —— Send 并行研究每道菜
//  7. 结果汇总器 meal_aggregator —— 合并并行结果
//
// 【条件路由兜底】
//  8. 礼貌拒绝 gentle_refuse —— 非烹饪话题
//
// 每个提示词只控制对应节点的行为边界，
// 和 CHEF_SYSTEM_PROMPT 互不干扰。
